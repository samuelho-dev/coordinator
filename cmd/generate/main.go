// Command generate emits public JSON schemas and native-adapter TypeScript bindings.
// Run from the repository root with json-schema-to-typescript's json2ts on PATH:
// go run ./cmd/generate
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"sort"

	"github.com/google/jsonschema-go/jsonschema"
	"github.com/samuelho-dev/coordinator/internal/wire"
)

func main() {
	names := []string{"SessionRef", "SessionPresence", "SessionInspection", "SessionListInput", "SessionListOutput", "SessionInspectInput", "ListMachine", "ListSession", "NativeSnapshot", "NativeEvent", "NativeNotice", "NativeMessage", "MessageCaller", "MessageSendParams", "MessageReplyParams", "MessageSendInput", "MessageReplyInput", "MessageGetInput", "Message", "MessageRecord", "ConnectorMessageAck"}
	sort.Strings(names)
	defs := map[string]*jsonschema.Schema{}
	properties := map[string]*jsonschema.Schema{}
	for _, name := range names {
		s, err := wire.Schema(name)
		must(err)
		defs[name] = s
		properties[name] = &jsonschema.Schema{Ref: "#/definitions/" + name}
	}
	bundle := &jsonschema.Schema{Schema: "http://json-schema.org/draft-07/schema#", Title: "WireTypes", Type: "object", Definitions: defs, Properties: properties, Required: names}
	b, err := json.MarshalIndent(bundle, "", "  ")
	must(err)
	b = append(b, '\n')
	must(os.MkdirAll("integrations", 0755))
	must(os.WriteFile("integrations/schema.generated.json", b, 0644))

	boundaryNames := []string{"NativeSnapshot", "SessionRef", "SessionListInput", "SessionInspectInput", "MessageSendParams", "MessageReplyParams", "MessageGetInput", "Message", "MessageRecord"}
	boundaryDefs := map[string]*jsonschema.Schema{}
	boundaryProperties := map[string]*jsonschema.Schema{}
	for _, name := range boundaryNames {
		boundaryDefs[name] = defs[name]
		boundaryProperties[name] = properties[name]
	}
	bundle.Definitions, bundle.Properties, bundle.Required = boundaryDefs, boundaryProperties, boundaryNames
	b, err = json.Marshal(bundle)
	must(err)
	cmd := exec.Command("json2ts", "--no-additionalProperties", "--no-banner")
	cmd.Stdin = bytes.NewReader(b)
	out, err := cmd.Output()
	must(err)
	var ts bytes.Buffer
	ts.WriteString("// Generated by cmd/generate; do not edit.\n")
	ts.Write(out)
	for _, name := range []string{"SessionListInput", "SessionInspectInput", "MessageSendParams", "MessageReplyParams", "MessageGetInput"} {
		schema, err := json.Marshal(defs[name])
		must(err)
		fmt.Fprintf(&ts, "\nexport const %sSchema = %s as const;\n", name, schema)
	}
	must(os.WriteFile("integrations/wire.generated.ts", ts.Bytes(), 0644))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
